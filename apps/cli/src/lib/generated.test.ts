import { describe, expect, it } from "vitest";
import type { Hunk } from "@collagen/review-web/data";
import { generatedBy } from "./generated";
import { groupByUnit } from "./units";

const hunk = (file: string, texts: ReadonlyArray<string>): Hunk => ({
  id: `${file}#0`,
  file,
  header: "@@",
  newStart: 1,
  newLines: texts.length,
  lines: texts.map((text, index) => ({ kind: "+" as const, text, new: 1 + index })),
});

describe("a file a tool wrote or a test recorded", () => {
  it("is told by its name", () => {
    expect(["src/__snapshots__/Button.test.tsx.snap", "api/user.pb.go", "gen/schema_pb2.py", "src/routeTree.gen.ts", "public/app.min.js", "src/__generated__/types.ts", "src/button.ts"].map((file) => generatedBy(file, null))).toEqual([
      "a test snapshot",
      "protoc",
      "protoc",
      "TanStack Router",
      "a minifier",
      "a code generator",
      null,
    ]);
  });

  it("is told by what its first comment says, naming the tool when it does", () => {
    expect(generatedBy("api/user.go", ["// Code generated by protoc-gen-go. DO NOT EDIT.", "package api"])).toBe("protoc-gen-go");
    expect(generatedBy("schema.ts", ["/**", " * @generated", " */"])).toBe("a code generator");
    expect(generatedBy("types.py", ["# This file was automatically generated by datamodel-codegen."])).toBe("datamodel-codegen");
  });

  it("is never code that only mentions a marker", () => {
    expect(generatedBy("src/rules.ts", ['const MARKER = "DO NOT EDIT";'])).toBe(null);
  });

  it("is read apart before the tests: a snapshot named as a test is no test", () => {
    const snapshot = hunk("src/Button.test.tsx.snap", ["exports[`Button 1`] = `<button />`;"]);
    const grouped = groupByUnit({ decisions: [], forks: [] }, [snapshot], new Map(), () => ({ after: snapshot.lines.map((line) => line.text), before: null }));
    expect(grouped.tests).toEqual([]);
    expect(grouped.generated?.map((file) => [file.file, file.by, file.added])).toEqual([["src/Button.test.tsx.snap", "a test snapshot", 1]]);
    expect(grouped.units).toEqual([]);
  });
});
